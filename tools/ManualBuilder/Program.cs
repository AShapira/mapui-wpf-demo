using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

var check = args.Contains("--check");
var root = args.FirstOrDefault(a => a != "--check") ?? Directory.GetCurrentDirectory();
root = Path.GetFullPath(root);
if (!File.Exists(Path.Combine(root, "OgcDemo.slnx"))) throw new Exception("Run from the repository root, or pass its path.");
var manifest = JsonSerializer.Deserialize<Lesson[]>(File.ReadAllText(Path.Combine(root,"docs/tutorial.json")),new JsonSerializerOptions {PropertyNameCaseInsensitive=true})!;
var outputs = new Dictionary<string,string>();
var included = new HashSet<string>();
string Anchor(string path) => "file-" + Regex.Replace(path.ToLowerInvariant(),"[^a-z0-9]","-");
string Source(string path, bool standalone)
{
    included.Add(path);
    var content=File.ReadAllText(Path.Combine(root,path)).Replace("\r\n","\n").TrimEnd();
    var lang=Path.GetExtension(path) switch {".cs"=>"csharp",".json"=>"json",".geojson"=>"json",".ps1"=>"powershell",".csproj" or ".props" or ".slnx" or ".Config" or ".xaml"=>"xml",_=>"text"};
    return $"\n<a id=\"{Anchor(path)}\"></a>\n\n### `{path}`\n\n" + (standalone ? "" : $"Source SHA-256: `{Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(content+"\n")))}`\n\n") +
        $"``````{lang}\n{content}\n``````\n";
}
string ManualLinks(string prose, string file) => Regex.Replace(prose,@"\]\(([^)]+)\)",m =>
{
    var target=m.Groups[1].Value;
    if(target.StartsWith('#') || Uri.TryCreate(target,UriKind.Absolute,out _)) return m.Value;
    var path=Path.GetRelativePath(root,Path.GetFullPath(Path.Combine(root,Path.GetDirectoryName(file)!,target.Split('#')[0]))).Replace('\\','/');
    if(path=="docs/BUILD-GUIDE.md") return "](#contents)";
    return "](#"+Anchor(path)+")";
});
var manual=new StringBuilder("# Build a .NET 10 WPF GIS Application with Mapsui and OGC Services\n\nGenerated from the reference project. English tutorial, complete source, tests, and configuration.\n\nDo not edit this file; edit docs/templates and source, then run ManualBuilder.\n\n## Contents\n\n");
foreach(var lesson in manifest) manual.AppendLine($"- [{lesson.Title}](#{Anchor(lesson.Output)})");
foreach(var lesson in manifest)
{
    var prose=File.ReadAllText(Path.Combine(root,lesson.Template)).Replace("\r\n","\n").TrimEnd()+"\n";
    var chapter=new StringBuilder("<!-- Generated by ManualBuilder. Edit the matching docs/templates file. -->\n\n"+prose);
    manual.Append($"\n<a id=\"{Anchor(lesson.Output)}\"></a>\n\n{ManualLinks(prose,lesson.Output)}");
    if(lesson.Sources.Length>0) { chapter.Append("\n## Complete source for this lesson\n"); manual.Append("\n## Complete source for this lesson\n"); }
    foreach(var path in lesson.Sources)
    {
        var alreadyIncluded=included.Contains(path); chapter.Append(Source(path,true));
        if(alreadyIncluded) manual.Append($"\nComplete source: [{path}](#{Anchor(path)}) (listed earlier, unchanged).\n");
        else manual.Append(Source(path,false));
    }
    outputs[lesson.Output]=chapter.ToString();
}
var extras = new[]{"README.md","LLM_CONTEXT.md","docs/configuration.md","docs/api-reference.md","docs/requirements.md","docs/validation.md","docs/extensions/advanced.md"};
foreach(var path in extras)
{
    manual.Append($"\n<a id=\"{Anchor(path)}\"></a>\n\n");
    manual.Append(ManualLinks(File.ReadAllText(Path.Combine(root,path)).Replace("\r\n","\n"),path)); manual.AppendLine();
}
manual.Append("\n# Remaining project files\n\nTogether with the lesson listings, these reproduce the reference project. Generated bin/obj, private settings, and validation tooling are excluded.\n");
var sourceRoots=new[]{"src","tests","tools","scripts","samples"};
var files=sourceRoots.SelectMany(d=>Directory.EnumerateFiles(Path.Combine(root,d),"*",SearchOption.AllDirectories))
    .Where(p=>!p.Replace('\\','/').Split('/').Any(s=>s is "bin" or "obj"))
    .Select(p=>Path.GetRelativePath(root,p).Replace('\\','/'))
    .Concat(manifest.Select(l=>l.Template))
    .Concat(extras)
    .Concat(new[]{".gitignore","global.json","Directory.Build.props","NuGet.Config","OgcDemo.slnx","docs/tutorial.json"})
    .Where(p=>!p.EndsWith("appsettings.local.json") && !included.Contains(p)).OrderBy(p=>p,StringComparer.Ordinal).ToArray();
foreach(var path in files) { var section=Source(path,false); if(extras.Contains(path)) section=section.Replace(Anchor(path),Anchor(path)+"-raw"); manual.Append(section); }
outputs["docs/BUILD-GUIDE.md"]=manual.ToString();
var guide=outputs["docs/BUILD-GUIDE.md"];
var withoutCode=Regex.Replace(guide,"(?ms)^``````.*?^``````[^\\n]*","");
var ids=Regex.Matches(withoutCode,"<a id=\"([^\"]+)\">").Select(m=>m.Groups[1].Value).ToHashSet();
ids.Add("contents");
foreach(Match m in Regex.Matches(withoutCode,@"\]\(#([^)]+)\)"))
    if(!ids.Contains(m.Groups[1].Value)) throw new Exception("Missing manual anchor: "+m.Groups[1].Value);
int changed=0;
foreach(var (path, rawContent) in outputs)
{
    var content=rawContent.Replace("\r\n","\n");
    var full=Path.Combine(root,path);
    if(File.Exists(full) && File.ReadAllText(full).Replace("\r\n","\n")==content) continue;
    changed++; if(check) Console.WriteLine("Stale or missing: "+path);
    else { Directory.CreateDirectory(Path.GetDirectoryName(full)!); File.WriteAllText(full,content,new UTF8Encoding(false)); }
}
// Validate local links in authored documentation. Code fences are removed first.
foreach(var file in extras.Concat(manifest.Select(l=>l.Template)))
{
    var text=File.ReadAllText(Path.Combine(root,file));
    text=Regex.Replace(text,"(?ms)^```.*?^```[^\\n]*","");
    foreach(Match m in Regex.Matches(text,@"\]\(([^)]+)\)"))
    {
        var target=m.Groups[1].Value.Split('#')[0];
        if(target.Length==0 || Uri.TryCreate(target,UriKind.Absolute,out _)) continue;
        // Templates use links relative to their generated chapter directory (same depth).
        if(!File.Exists(Path.GetFullPath(Path.Combine(root,Path.GetDirectoryName(file)!,target))) && !Directory.Exists(Path.GetFullPath(Path.Combine(root,Path.GetDirectoryName(file)!,target))))
            throw new Exception($"Broken link in {file}: {target}");
    }
}
Console.WriteLine(check ? $"Documentation check: {changed} stale outputs; local links valid." : $"Generated {outputs.Count} documents; {included.Count} source files included; local links valid.");
return check && changed>0 ? 1 : 0;
record Lesson(string Title,string Template,string Output,string[] Sources);
